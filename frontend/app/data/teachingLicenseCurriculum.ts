import { CourseOrMinorItem, GroupRule, pick, req } from './coursesAndMinorsCurriculum';

export type LicenseLevel = '中学校一種' | '高等学校一種';

export interface TeachingLicenseDef {
  department: string;
  subject: string;
  levels: LicenseLevel[];
  page: string;
  requiredCourses: CourseOrMinorItem[];
  electiveRequiredCourses: CourseOrMinorItem[];
  groupRules: GroupRule[];
  // 各教科教育法（教職コース科目。Ⅲ・Ⅳは中学校で必修、高等学校で選択）
  methodCourses: string[];
  notes: string[];
}

