const choose = (group: string, label: string, n: number, credits: number, ...names: string[]) => ({
  items: pick(group, credits, ...names),
  rule: { group, label, minCourses: n } as GroupRule
});
const eitherOr = (group: string, label: string, a: string[], b: string[], credits = 2) => ({
  items: pick(group, credits, ...a, ...b),
  rule: { group, label, alternatives: [{ label: 'A', courses: a }, { label: 'B', courses: b }] } as GroupRule
});

function license(
  department: string,
  subject: string,
  levels: LicenseLevel[],
  page: string,
  requiredCourses: CourseOrMinorItem[],
  groups: { items: CourseOrMinorItem[]; rule: GroupRule }[],
  methodCourses: string[],
  notes: string[] = []
): TeachingLicenseDef {
  return {
    department,
    subject,
    levels,
    page,
    requiredCourses,
    electiveRequiredCourses: groups.flatMap((g) => g.items),
    groupRules: groups.map((g) => g.rule),
    methodCourses,
    notes
  };
}

const method = (base: string, upTo: 2 | 4) => ['Ⅰ', 'Ⅱ', 'Ⅲ', 'Ⅳ'].slice(0, upTo).map((n) => `${base}${n}`);

